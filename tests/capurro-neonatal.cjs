'use strict';
const assert=require('node:assert/strict'),fs=require('node:fs'),vm=require('node:vm');
const src=fs.readFileSync('capurro.html','utf8'),home=fs.readFileSync('index.html','utf8'),sw=fs.readFileSync('sw.js','utf8');
const script=src.match(/<script>([\s\S]*?)<\/script>/);
assert.ok(script,'Capurro script exists');new vm.Script(script[1]);
const p=script[1].slice(script[1].indexOf('const CAPURRO_FIELDS='),script[1].indexOf('const $=id'));
const context={};vm.runInNewContext(p+'\nthis.logic={CAPURRO_FIELDS,CAPURRO_MODES,capurroCalculate}',context);
const {CAPURRO_FIELDS:fields,CAPURRO_MODES:modes,capurroCalculate:calc}=context.logic;
assert.deepEqual(Array.from(modes.somatic.keys),['ear','mammary','nipple','skin','soles']);assert.equal(modes.somatic.constant,204);
assert.deepEqual(Array.from(modes.neuro.keys),['ear','mammary','skin','soles','scarf','head']);assert.equal(modes.neuro.constant,200);
assert.deepEqual(Array.from(fields.ear.options,o=>o[0]),[0,8,16,24]);
assert.deepEqual(Array.from(fields.scarf.options,o=>o[0]),[0,6,12,18]);
assert.deepEqual(Array.from(fields.head.options,o=>o[0]),[0,4,8,12]);
assert.equal(calc('somatic',{}),null,'never treat missing entries as zero');
assert.equal(calc('somatic',{ear:0,mammary:0,nipple:0,skin:0,soles:0}).days,204);
const term=calc('somatic',{ear:16,mammary:10,nipple:10,skin:10,soles:10});
assert.equal(term.days,260);assert.equal(term.classification,'A término');
const older=calc('somatic',{ear:24,mammary:15,nipple:15,skin:20,soles:20});
assert.equal(older.days,298);assert.equal(older.classification,'Postérmino');
const neuro=calc('neuro',{ear:24,mammary:15,skin:20,soles:20,scarf:18,head:12});
assert.equal(neuro.days,309);assert.equal(neuro.weeks,44);assert.equal(neuro.remainingDays,1);
assert.equal(calc('neuro',{ear:24,mammary:15,skin:20,soles:20,scarf:18}),null);
assert.equal(calc('somatic',{ear:7,mammary:15,nipple:15,skin:20,soles:20}),null,'reject unvalidated points');
assert.match(src,/kidbum-theme/);assert.match(src,/NOM-007-SSA2-2016/);
assert.match(home,/data-capurro-open/);assert.match(home,/src="\.\/assets\/pediatria-portada\.webp"/);assert.match(home,/background-image:url\(\.\/assets\/pediatria-portada\.webp\)/);
assert.ok(fs.existsSync('assets/pediatria-portada.webp'),'The calculator card artwork exists');
assert.match(sw,/'\.\/capurro\.html'/);assert.match(sw,/capurro-illustrated/);
console.log('Capurro PASS: both validated modes, boundary scores, incomplete fields, illustrated card, PWA');
