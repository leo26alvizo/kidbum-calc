'use strict';
const assert=require('node:assert/strict'),fs=require('node:fs'),vm=require('node:vm');
const html=fs.readFileSync('index.html','utf8');
const inline=[...html.matchAll(/<script(?:[^>]*)>([\s\S]*?)<\/script>/g)].map(x=>x[1]).filter(x=>x.trim());
const root={};root.window=root;root.globalThis=root;
vm.runInNewContext(fs.readFileSync('assets/startup-bundle.js','utf8'),root,{timeout:10000});
vm.runInNewContext(inline[0],root,{timeout:10000});
const gas=fs.readFileSync('assets/guardia-gasometria.js','utf8');
new vm.Script(gas);vm.runInNewContext(gas,root);
const kit=root.KidBumGasometria,engine=root.KidBumEngine;
assert.ok(kit&&engine);
const input={pop:'adult',sample:'arterial',paired:'yes',primary:'yes',ph:'7.28',paco2:'29',hco3:'14',na:'140',cl:'106',alb:'2',agref:'12',hcoref:'24'};
const ag=engine.calculate('anion',{na:140,cl:106,hco3:14,alb:2});
assert.equal(ag.value,20);
assert.equal(ag.correctedAG,25);
assert.equal(engine.calculate('anion',{na:140,cl:106,hco3:14}).correctedAG,undefined);
let result=kit.evaluate(input,engine);
assert.equal(result.value,20);
assert.ok(result.items.some(x=>x.includes('25.0 mmol/L')));
assert.ok(result.items.some(x=>x.includes('27.0–31.0 mmHg')));
assert.ok(result.items.some(x=>x.includes('1.30')),'Delta ratio uses AG adjusted for albumin');
assert.equal(engine.calculate('winter',{hco3:14,paco2:29}).value,29);
assert.ok(kit.evaluate({...input,sample:'venous'},engine).pending);
assert.ok(kit.evaluate({...input,pop:'other'},engine).pending);
assert.ok(kit.evaluate({...input,paired:'no'},engine).pending);
assert.ok(kit.evaluate({...input,primary:''},engine).pending);
assert.ok(kit.evaluate({...input,na:''},engine).error);
assert.ok(kit.evaluate({...input,na:'x'},engine).error);
assert.ok(kit.evaluate({...input,ph:'10'},engine).error);
assert.ok(kit.evaluate({...input,hco3:'0'},engine).error);
assert.ok(kit.evaluate({...input,alb:'2,2'},engine).items);
assert.ok(kit.evaluate({...input,alb:''},engine).warnings.some(x=>/Albúmina/.test(x)));
result=kit.evaluate({...input,agref:'',hcoref:''},engine);
assert.ok(result.warnings.some(x=>/Delta ratio pendiente/.test(x)));
assert.ok(result.items.every(x=>!x.includes('Delta ratio')));
result=kit.evaluate({...input,primary:'unknown'},engine);
assert.ok(result.items.every(x=>!x.includes('Winter:')));
assert.ok(result.items.every(x=>!x.includes('Delta ratio ')));
result=kit.evaluate({...input,ph:'7.17'},engine);
assert.ok(result.warnings.some(x=>/urgente/.test(x)));
const tr=engine.calculate('anion',{na:140,cl:104,hco3:23});
assert.equal(tr.value,13,'Original AG equation preserved');
assert.ok(html.includes("window.KidBumGasometria.render(main,engine"));
assert.ok(html.includes("id:'gasometria'"));
assert.match(html,/assets\/guardia-gasometria\.js/);
assert.doesNotMatch(gas,/fetch\(|XMLHttpRequest|api\.openai\.com/);
console.log('Gasometria PASS: engine reuse, corrected albumin AG, Winter, delta, sample safety, missing data and numeric limits.');
