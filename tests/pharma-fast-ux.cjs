assert.ok(lib.searchConditions('gata con alas').length===0,'No hallucinated disease routes');
assert.equal(lib.byId.warfarina.highRisk,true,'Existing ISMP labels preserved');
assert.equal(lib.byId.hidralazina.lasaPairs.length,1,'Existing LASA preserved');
assert.match(page,/id="pharma-view-nav"/);
