'use strict';
const fs=require('node:fs');
const assert=require('node:assert/strict');
const crypto=require('node:crypto');
const source=fs.readFileSync('index.html','utf8');
const cache=fs.readFileSync('sw.js','utf8');
const image=fs.readFileSync('assets/geriatria-portada.webp');
assert.ok(source.includes("const categories=['Todas'")&&source.includes("'Geriatría','Endocrinología y Diabetes']"),'Geriatría is included among filter chips');
assert.match(source,/const ordered=\[[^\]]*'Gastroenterología','Geriatría','Ginecología y obstetricia'/,'Home category cards include Geriatría between Gastro and Ginecología');
assert.match(source,/c==='Geriatría'\?' atlas-gineco-feature atlas-geriatria-feature'/,'Geriatría uses featured card style');
assert.match(source,/c==='Geriatría'\?'<img class="atlas-category-illustration atlas-gineco-photo atlas-geriatria-photo" src="\.\/assets\/geriatria-portada\.webp"/,'The portrait is the supplied local asset');
assert.match(source,/\.atlas-geriatria-feature \.atlas-category-copy\{/,'Geriatrics has a protected text panel');
assert.match(source,/\.atlas-geriatria-feature \.atlas-geriatria-photo\{[\s\S]*?object-fit:cover;/,'Portrait crops responsively');
assert.match(source,/const count=calculatorCount\(c\)/,'Category card uses dynamic counter');
const catalog=source.slice(source.indexOf('const externalCalculators='),source.indexOf('const calculatorCount='));
const geriatricEntries=[...catalog.matchAll(/\{id:'([^']+)',category:'Geriatría',href:'\.\/expansion-20\.html#([^']+)',image:'([^']+)'\}/g)];
assert.deepEqual(geriatricEntries.map(x=>x[1]),['at4','frailty'],'Geriatrics opens the 4AT and CFS tools');
assert.equal(geriatricEntries.length,2);
const newEntries=[...catalog.matchAll(/\{id:'([^']+)',category:'Geriatría',href:'\.\/geriatria-escalas\.html#([^']+)',image:'([^']+)'\}/g)];
assert.equal(newEntries.length,8,'Eight additional Geriatrics calculators are linked');
assert.equal(newEntries.length+geriatricEntries.length,10,'Geriatrics features 10 calculators');
assert.match(source,/data-featured="\$\{enc\(c\)\}"/);
assert.match(source,/category=button\.dataset\.featured;renderHome\(false\)/,'Card opens filter by category');
assert.equal(image.toString('ascii',0,4),'RIFF');
assert.equal(image.toString('ascii',8,12),'WEBP');
assert.equal(image.readUInt32LE(4)+8,image.length,'WebP container bytes are intact');
assert.equal(image.length,28586,'The supplied portrait has an optimized, verified file size');
const gitHash=crypto.createHash('sha1').update(Buffer.from('blob '+image.length+'\0')).update(image).digest('hex');
assert.equal(gitHash,'63a8779a1319f5201801bf30d5cc6db3a0227990','Uploaded Geriatrics portrait must match original optimized bytes exactly');
assert.match(cache,/'\.\/assets\/geriatria-portada\.webp'/,'Image available offline through the PWA');
assert.match(cache,/geriatria-home-card-v1/,'Cache is refreshed');
console.log('Geriatrics home card PASS: portrait integrity, 10 calculator dynamic links, category styling, offline');
