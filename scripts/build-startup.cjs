'use strict';
/* Rebuild KidBum CALC startup bundle without modifying medical source modules.
 * Run: node scripts/build-startup.cjs
 * Check in generated assets/startup-bundle.js alongside clinical source updates.
 */
const fs=require('node:fs');
const path=require('node:path');
const root=path.resolve(__dirname,'..');
const modules=[
 'who-wfa','who-lhfa','who-hcfa','who-bmifa','who-wfl','who-wfh',
 'pediatric-module','pediatric-ward','hospital-module','advanced-module',
 'neurology-module','neurology-advanced','cardiology-module','critical-module','critical-advanced'
].map(name=>'assets/'+name+'.js');
const header='/* KidBum CALC v0.10.2 — Clinical startup bundle.\n'
 +' * Generated by concatenating original clinical modules IN THE SAME ORDER as index.html.\n'
 +' * Originals are preserved in assets/ for maintainability and regression tests.\n'
 +' * No formulas or clinical constants changed.\n'
 +' */\n';
const result=header+modules.map(p=>';\n/* Original source: '+p+' */\n'
 +fs.readFileSync(path.join(root,p),'utf8')+'\n').join('\n');
fs.writeFileSync(path.join(root,'assets/startup-bundle.js'),result,'utf8');
console.log('Bundled '+modules.length+' untouched clinical modules ('+Buffer.byteLength(result,'utf8')+' bytes).');
